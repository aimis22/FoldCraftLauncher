/*
 * fg_config.h - 编译期常量
 *
 * 这些数字来自实测，不是拍脑袋。改之前先看注释里的理由。
 *
 * 设备基线（小米平板 / 骁龙 8s Gen 4 / Adreno 825 / 8GB / 3200x2136 144Hz）：
 *   内部渲染 1920x1280 时，原版 + Sodium 视距 12 峰值 300 fps ≈ 3.3ms/帧
 *   → 算力余量极大，限制不在 GPU
 */

#ifndef FG_CONFIG_H
#define FG_CONFIG_H

/* ------------------------------------------------------------------ */
/* 刷新率与锁帧                                                        */
/* ------------------------------------------------------------------ */

/*
 * 目标上屏刷新率。
 *
 * 实测这台机器的面板目前只给到 120Hz（小米平板默认值，144Hz 要在系统显示设置里
 * 手动选，并且要开 FCL Debug 里的 Request Max Refresh Rate）。所以先按 120 配，
 * 这样槽位和锁帧数字才是对的。等面板真跑到 144 再改成 144。
 *
 * 关键关系：插帧是「在两次真实帧之间塞 FG_MULT-1 帧」，
 * 所以 输出 = 基帧 x FG_MULT。要 120Hz 输出，基帧就必须锁 60。
 * 锁帧不是性能妥协，是数学前提 —— 游戏自己跑 300 帧时，
 * BufferQueue 一直被新帧覆盖，插帧帧根本轮不到上屏。
 */
#define FG_TARGET_HZ        120

/* 插帧倍率。2 = 每两帧之间塞一帧。3 档算力也够，但伪影明显更多，后期再试 */
#define FG_MULT             2

/* 游戏侧应锁到的帧率（在 options.txt 里写 maxFramerate） */
#define FG_BASE_HZ          (FG_TARGET_HZ / FG_MULT)

/* 基帧每帧的槽位（毫秒）。144Hz/2 时是 13.89ms */
#define FG_SLOT_MS          (1000.0 / (double) (FG_BASE_HZ))

/* ------------------------------------------------------------------ */
/* M0 验收线                                                           */
/* ------------------------------------------------------------------ */

/*
 * capture + extra-present 的合计 GPU 时间。
 * 这两个数决定整件事做不做，别改。
 *
 *   < 2.0ms  继续做光流（预计可行）
 *   2.0-3.5  只做 2x 精简档
 *   > 3.5ms  放弃，这条路在移动端不通
 */
#define FG_ACCEPT_MS        2.0
#define FG_ABORT_MS         3.5

/* 每累计多少帧打一行统计。300fps 下约 1 秒一行 */
#define FG_STATS_EVERY      300

/*
 * M0 基准模式：每次采集/呈现后插 glFinish，把 GPU 真正做完的时间测出来。
 * 关掉它测到的只是「命令提交时间」（通常 0.1ms 级），会把开销严重低估。
 * 代价是每帧多一次同步等待，所以只在测 M0 时开。
 * M1 之后关掉，改为看帧时间差值。
 */
#define FG_BENCH_FINISH     1

/* ------------------------------------------------------------------ */
/* 内存门控                                                            */
/* ------------------------------------------------------------------ */

/*
 * 1080p 级（1920x1280）全质量档约 79MB GPU 纹理，加显示缓冲约 140MB。
 * 8GB 机器后台干净时余量 2GB+，够用；余量低于这个数就降档或关掉。
 */
#define FG_MIN_FREE_MB      1500

/* 精简档：深度降到半分辨率（省约 12MB，并降一半深度带宽） */
enum {
    FG_TIER_FULL = 0,   /* 深度全分辨率 */
    FG_TIER_LITE = 1    /* 深度半分辨率 */
};

#define FG_DEFAULT_TIER     FG_TIER_FULL

/* ------------------------------------------------------------------ */
/* M1 开关                                                            */
/* ------------------------------------------------------------------ */

/*
 * 0 = 只跑 M0（采集 + 重复帧），用来量开销，画面看起来是「同一帧刷两次」
 * 1 = 启用 M1（LK 光流 + 双向 warp 合成），出真正的插值帧
 *
 * **先跑 0 拿到 [M0] 那一行数字，确认 total < 2ms 之后再改成 1。**
 * 直接开 1 的话，如果采集本身就超预算，你会分不清是采集贵还是合成贵。
 */
#define FG_M1_ENABLE        0

#endif /* FG_CONFIG_H */
